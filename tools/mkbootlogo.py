#!/usr/bin/env python3
"""Pre-render the Bergamota logo for the Enxerto boot screen into a C header.

  python3 tools/mkbootlogo.py [--size 320] [--out <worktree>/enxerto/bootlogo.h] [--preview png]

The logo (tools/assets/bergamota-logo.png, made by tools/make-boot-assets.swift) is composited on
Enxerto's BG_BOOT green, quantised to a 256-colour palette (index 0 = the background exactly)
and stored row by row with a tiny RLE:
    ctl 0x00-0x7f : run of ctl+1 pixels of the next byte
    ctl 0x80-0xff : (ctl & 0x7f)+1 literal pixel indices
Every row decodes to exactly W pixels, so Enxerto can stream rows straight into the framebuffer.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bergamota_img import BG as BG_BOOT, Canvas, crop_alpha, read_png, resize_rgba, write_png

HERE = os.path.dirname(os.path.abspath(__file__))


def median_cut(hist, n):
    """hist: {(r,g,b): count}. Returns n representative colours."""
    boxes = [list(hist.items())]
    while len(boxes) < n:
        boxes.sort(key=lambda b: -(len(b) > 1) * sum(c for _, c in b))
        box = boxes.pop(0)
        if len(box) < 2:
            boxes.append(box)
            break
        rng = [max(c[0][i] for c in box) - min(c[0][i] for c in box) for i in range(3)]
        ch = rng.index(max(rng))
        box.sort(key=lambda c: c[0][ch])
        half, acc, cut = sum(c for _, c in box) / 2, 0, 0
        for i, (_, c) in enumerate(box):
            acc += c
            if acc >= half:
                cut = i + 1
                break
        cut = min(max(cut, 1), len(box) - 1)
        boxes += [box[:cut], box[cut:]]
    pal = []
    for box in boxes:
        t = sum(c for _, c in box)
        pal.append(tuple(int(sum(col[i] * c for col, c in box) / t + 0.5) for i in range(3)))
    return pal


def rle_row(row):
    out, i, n = bytearray(), 0, len(row)
    lit = bytearray()

    def flush():
        nonlocal lit
        while lit:
            chunk, lit = lit[:128], lit[128:]
            out.append(0x80 | (len(chunk) - 1))
            out.extend(chunk)

    while i < n:
        j = i
        while j < n and row[j] == row[i] and j - i < 128:
            j += 1
        if j - i >= 3:
            flush()
            out += bytes([j - i - 1, row[i]])
            i = j
        else:
            lit.append(row[i])
            i += 1
    flush()
    return out


def decode(rle, w, h):
    px, p = [], 0
    for _ in range(h):
        row = []
        while len(row) < w:
            c = rle[p]; p += 1
            if c & 0x80:
                row += rle[p:p + (c & 0x7f) + 1]; p += (c & 0x7f) + 1
            else:
                row += [rle[p]] * (c + 1); p += 1
        assert len(row) == w
        px.append(row)
    assert p == len(rle)
    return px


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.join(HERE, "assets", "bergamota-logo.png"))
    ap.add_argument("--size", type=int, default=320)
    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "ios-beryllium-ios18", "enxerto", "bootlogo.h"))
    ap.add_argument("--preview")
    ap.add_argument("--bg", help="background RRGGBB instead of BG_BOOT (the kernel console logo uses 000000)")
    ap.add_argument("--dim", type=float, default=1.0, help="scale the logo's colours (console logo: dimmed under text)")
    ap.add_argument("--name", default="bootlogo", help="C identifier prefix")
    a = ap.parse_args()
    bg = tuple(int(a.bg[i:i + 2], 16) for i in (0, 2, 4)) if a.bg else BG_BOOT

    img = crop_alpha(read_png(a.src), pad=24)
    w0, h0, _ = img
    s = max(w0, h0)
    # square canvas, centred, so the logo is a W x W tile
    sq = Canvas(s, s, (0, 0, 0))
    big = (s, s, bytearray(s * s * 4))
    for y in range(h0):
        o = ((y + (s - h0) // 2) * s + (s - w0) // 2) * 4
        big[2][o:o + w0 * 4] = img[2][y * w0 * 4:(y + 1) * w0 * 4]
    small = resize_rgba(big, a.size, a.size)
    c = Canvas(a.size, a.size, bg)
    c.blit(small, 0, 0)
    W = H = a.size

    pixels = [tuple(int(v * a.dim + 0.5) for v in c.px[i * 3:i * 3 + 3]) for i in range(W * H)]
    BG = tuple(int(v * a.dim + 0.5) for v in bg)
    hist = {}
    for p in pixels:
        if p != BG:
            hist[p] = hist.get(p, 0) + 1
    pal = [BG] + median_cut(hist, 255)
    cache = {BG: 0}

    def nearest(p):
        v = cache.get(p)
        if v is None:
            v = min(range(len(pal)), key=lambda i: (pal[i][0] - p[0]) ** 2 + (pal[i][1] - p[1]) ** 2 + (pal[i][2] - p[2]) ** 2)
            cache[p] = v
        return v

    idx = [[nearest(pixels[y * W + x]) for x in range(W)] for y in range(H)]
    rle = bytearray()
    for row in idx:
        rle += rle_row(row)
    assert decode(rle, W, H) == idx

    with open(a.out, "w") as f:
        f.write("/* generated by tools/mkbootlogo.py from tools/assets/bergamota-logo.png: do not edit */\n")
        N = a.name
        f.write("#define %s_W %d\n#define %s_H %d\n" % (N.upper(), W, N.upper(), H))
        f.write("/* a8r8g8b8, index 0 = the background */\nstatic const unsigned int %s_pal[256] = {" % N)
        for i, (r, g, b) in enumerate(pal + [BG] * (256 - len(pal))):
            f.write("%s0xff%02x%02x%02x," % ("\n\t" if i % 8 == 0 else " ", r, g, b))
        f.write("\n};\n/* per-row RLE, see tools/mkbootlogo.py */\n")
        f.write("static const unsigned char %s_rle[%d] = {" % (N, len(rle)))
        for i, v in enumerate(rle):
            f.write("%s0x%02x," % ("\n\t" if i % 16 == 0 else "", v))
        f.write("\n};\n")
    print("%dx%d, %d colours, RLE %d bytes (raw %d) -> %s" % (W, H, len(pal), len(rle), W * H, a.out))
    if a.preview:
        out = bytearray()
        for row in idx:
            for v in row:
                out += bytes(pal[v])
        write_png(a.preview, W, H, out)


if __name__ == "__main__":
    main()
